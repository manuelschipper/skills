def coverage_table(inventory, ledger):
    files = ledger["files"] if ledger else inventory["files"]
    rows = []
    total_lines = sum(f["lines"] for f in files)
    unit = max(1, total_lines // 38) if total_lines else 1
    out = [f"COVERAGE                                              scale: one # = {fmt(unit)} lines"]
    out.append(f"  {'class':10} {'files':>6} {'lines':>9}  {'':38}  {'read':>5} {'bndry':>5} {'list':>5} {'uncov':>5} {'pend':>5}")
    for cls in CLASS_ORDER:
        group = [f for f in files if f["class"] == cls]
        if not group:
            continue
        lines = sum(f["lines"] for f in group)
        st = Counter(f.get("status", {"read": "pending", "boundary": "boundary-only", "listed": "listed"}[f["treatment"]]) for f in group)
        mark = bar(lines, unit, 38) if cls in READ_CLASSES else "." * len(bar(lines, unit, 38))
        out.append(f"  {cls:10} {len(group):6d} {fmt(lines):>9}  {mark:38}  {st['read-in-full']:5d} {st['boundary-only']:5d}"
                   f" {st['listed']:5d} {st['uncovered']:5d} {st['pending']:5d}")
        rows.append(cls)
    out.append(f"  {'total':10} {len(files):6d} {fmt(total_lines):>9}")
    out.append("  bars: '#' classes are read in full, '.' classes are boundary-checked or listed only")
    return "\n".join(out)


def exclusion_table(files):
    out = ["EXCLUSIONS  (not read in full; every count is from the inventory)"]
    groups = defaultdict(list)
    for f in files:
        if f["treatment"] != "read":
            groups[(f["class"], f["reason"])].append(f)
    if not groups:
        out.append("  none")
    for (cls, reason), group in sorted(groups.items()):
        dirs = Counter(str(Path(f["path"]).parent) for f in group)
        top = ", ".join(f"{d}/ ({n})" for d, n in dirs.most_common(3))
        out.append(f"  {cls:10} {len(group):5d} files  {fmt(sum(f['lines'] for f in group)):>9} lines  {reason}")
        out.append(f"  {'':10} {'':5}        {'':9}        in {top}")
    return "\n".join(out)


def area_of(path, depth=2):
    parts = Path(path).parts
    return "/".join(parts[:depth]) + "/" if len(parts) > depth else "/".join(parts[:-1]) + "/" if len(parts) > 1 else "./"


def map_section(ledger):
    files = ledger["files"]
    findings = ledger["findings"]
    per_area = defaultdict(lambda: {"files": 0, "lines": 0, "findings": 0, "high": 0, "classes": Counter()})
    for f in files:
        area = area_of(f["path"])
        entry = per_area[area]
        entry["files"] += 1
        entry["lines"] += f["lines"]
        entry["classes"][f["treatment"]] += 1
    for f in findings:
        entry = per_area[area_of(f["path"])]
        entry["findings"] += 1
        entry["high"] += f["severity"] == "HIGH"
    most = max((e["findings"] for e in per_area.values()), default=0)
    unit = max(1, -(-most // 20))
    out = [f"MAP                                                   scale: one # = {unit} findings"]
    out.append(f"  {'area':38} {'files':>6} {'lines':>9}  {'findings':20}  note")
    for area in sorted(per_area):
        e = per_area[area]
        note = []
        if e["high"]:
            note.append(f"{e['high']} HIGH")
        if e["classes"]["boundary"] == e["files"]:
            note.append("boundary only")
        elif e["classes"]["listed"] == e["files"]:
            note.append("listed only")
        out.append(f"  {area:38} {e['files']:6d} {fmt(e['lines']):>9}  {bar(e['findings'], unit, 16):16} {e['findings']:3d}  {', '.join(note)}")
    return "\n".join(out)


def heat_section(ledger, properties):
    findings = ledger["findings"]
    areas = Counter(area_of(f["path"]) for f in findings)
    top = [a for a, _ in areas.most_common(7)]
    rest = sorted(set(areas) - set(top))
    columns = top + (["other"] if rest else [])
    cells = defaultdict(Counter)
    for f in findings:
        area = area_of(f["path"])
        cells[f["property"]][area if area in top else "other"] += 1
    glyph = lambda n: "." if n == 0 else ":" if n <= 2 else "+" if n <= 5 else "#"
    out = ["HEAT GRID  findings per property and area   . = 0   : = 1-2   + = 3-5   # = 6 or more"]
    if not findings:
        return out[0] + "\n  no findings"
    width = 52
    header = "  " + " " * (width + 4) + " ".join(f"{i + 1:>3}" for i in range(len(columns)))
    out.append(header)
    for index, prop in enumerate(properties, 1):
        row = " ".join(f"{glyph(cells[prop][c]):>3}" for c in columns)
        out.append(f"  {index:2d} {prop[:width]:{width}} {row}   {sum(cells[prop].values()):3d}")
    out.append("  columns:")
    for index, column in enumerate(columns, 1):
        label = column if column != "other" else f"other ({len(rest)} areas)"
        out.append(f"    {index:2d} {label}")
    return "\n".join(out)


def property_ledger(ledger, properties, narrative):
    findings = ledger["findings"]
    na = narrative.get("properties_not_applicable", {})
    checks = narrative.get("property_checks", {})
    out = ["PROPERTY LEDGER                                       scale: one # = 1 finding"]
    out.append(f"  {'#':>2} {'property':52} {'HIGH':>4} {'MED':>4} {'LOW':>4}  status")
    for index, prop in enumerate(properties, 1):
        group = [f for f in findings if f["property"] == prop]
        counts = Counter(f["severity"] for f in group)
        if prop in na:
            status = "n/a, because:"
        elif group:
            status = bar(len(group), 1, 24)
        elif checks.get(prop):
            status = "clean, checked by:"
        else:
            status = "UNVERIFIED: no property_checks entry"
        out.append(f"  {index:2d} {prop[:52]:52} {counts['HIGH']:4d} {counts['MED']:4d} {counts['LOW']:4d}  {status}")
        if status.startswith("clean") or prop in na:
            out.append(field("", checks.get(prop) or na.get(prop), gutter=8, label_width=0).replace("         ", "        ", 1))
    out.append(f"  {'total':55} {sum(f['severity'] == 'HIGH' for f in findings):4d}"
               f" {sum(f['severity'] == 'MED' for f in findings):4d} {sum(f['severity'] == 'LOW' for f in findings):4d}")
    return "\n".join(out)


def reach_section(trials):
    out = ["SEARCH REACH   [x] reached (path in audit.json)  [ ] not reached  [-] n/a  [?] path missing"]
    if not trials:
        return out[0] + "\n  no concepts recorded in vocabulary.json"
    out.append(f"  {'concept':24} {'spellings':30} owner wire  cntr  test  absn  {'hits':>6}")
    keys = ("owner", "wiring", "contract", "tests", "absence")
    totals = Counter()
    for t in trials:
        marks = "  ".join(f"[{t['reach'][k]['mark']}]" for k in keys)
        for k in keys:
            if t["reach"][k]["mark"] in ("x", " "):
                totals[k + "_n"] += 1
                totals[k] += t["reach"][k]["mark"] == "x"
        out.append(f"  {t['concept'][:24]:24} {', '.join(t['spellings'])[:30]:30} {marks}  {fmt(t['hits']):>6}")
    out.append("  reached: " + "  ".join(f"{k} {totals[k]}/{totals[k + '_n']}" for k in keys if totals[k + "_n"]))
    out.append("  hits = git grep -nw count of every spelling across inventoried files")
    return "\n".join(out)


def card(finding, packet_of):
    f = finding
    head = f"{f['id']}  {f['severity']:4}  {f['property']}"
    out = [head + (f"   packet {packet_of[f['id']]}" if f["id"] in packet_of else ""), "-" * len(head)]
    out.append(f"  where     {f['path']}:{f['line']}")
    for line in str(f["evidence"]).splitlines():
        out.append(f"    | {ascii_safe(line.rstrip())}")
    out.append(field("why", f["observation"]))
    for search in f.get("searches", []):
        out.append(f"  search    \"{search.get('term', '')}\" -> {search.get('note', '')}")
    blast = f.get("blast")
    if blast:
        by_class = ", ".join(f"{k} {v}" for k, v in sorted(blast["by_class"].items()))
        out.append(f"  blast     `{blast['symbol']}`: {blast['hits']} hits in {blast['files']} files ({by_class or 'none'})")
        for hit in blast["paths"][:6]:
            out.append(f"              {hit}")
        if len(blast["paths"]) > 6:
            out.append(f"              +{len(blast['paths']) - 6} more in audit.json")
        if "new_symbol" in blast:
            out.append(f"  new name  `{blast['new_symbol']}`: {blast['new_symbol_hits']} existing hits"
                       + (" (free)" if blast["new_symbol_hits"] == 0 else " (collision, choose another)"))
    if f.get("recipe"):
        for index, step in enumerate(f["recipe"], 1):
            out.append(field("recipe" if index == 1 else "", f"{index}. {step}"))
    if f.get("decision"):
        out.append(field("decision", f["decision"].get("question", "")))
        for option in f["decision"].get("options", []):
            out.append(field("", f"- {option}"))
    for index, check in enumerate(f.get("accept", [])):
        argv = " ".join(check["argv"])
        out.append(f"  {'accept' if index == 0 else '      '}    {argv:48} -> {check['expect']}")
    return "\n".join(ascii_safe(line) for line in out)


def one_liner(finding, packet_of):
    f = finding
    action = f"recipe: {f['recipe'][0]}" if f.get("recipe") else f"decision: {f['decision'].get('question', '')}"
    accept = f.get("accept") or []
    tail = f"; accept: {' '.join(accept[0]['argv'])} -> {accept[0]['expect']}" if accept else ""
    first = f"{f['id']}  {f['severity']:4} {f['property'][:40]:40} {f['path']}:{f['line']}" + (f"  {packet_of[f['id']]}" if f["id"] in packet_of else "")
    return ascii_safe(first) + "\n" + field("", f"{action}{tail}", gutter=7, label_width=0).replace("        ", "       ", 1)


def packets_section(ledger):
    packets = ledger.get("packets", [])
    out = ["WORK PACKETS  in dependency order; a packet is done when every accept line holds"]
    if not packets:
        return out[0] + "\n  none recorded in packets.json"
    ids = {f["id"]: f for f in ledger["findings"]}
    for packet in packets:
        sev = Counter(ids[fid]["severity"] for fid in packet["findings"] if fid in ids)
        out.append("")
        out.append(f"  {packet['id']}  {packet['title'][:56]:56} {len(packet['findings']):3d} findings"
                   f"  files {len(packet['files']):3d}  tests {len(packet['tests']):3d}")
        out.append(f"        {' '.join(packet['findings'])}  (HIGH {sev['HIGH']}, MED {sev['MED']}, LOW {sev['LOW']})")
        if packet.get("after"):
            out.append(f"        after: {', '.join(packet['after'])}")
        if packet.get("note"):
            out.append(field("", packet["note"], gutter=8, label_width=0).replace("         ", "        ", 1))
        for index, check in enumerate(packet.get("accept", [])):
            out.append(f"        {'accept:' if index == 0 else '       '} {' '.join(check['argv']):44} -> {check['expect']}")
    if ledger.get("unassigned_findings"):
        out.append("")
        out.append(f"  not in any packet: {' '.join(ledger['unassigned_findings'])}")
    return "\n".join(ascii_safe(line) for line in out)


def appendix(ledger):
    out = ["LEDGER"]
    out.append("  shards")
    for s in ledger["shards"]:
        out.append(f"    {s['id']:6} {s['status']:10} {len(s['files']):4d} files  {fmt(s['lines']):>8} lines" + (f"  parent {s['parent']}" if s["parent"] else ""))
    uncovered = [f for f in ledger["files"] if f["status"] in ("uncovered", "pending")]
    out.append(f"  uncovered or pending files: {len(uncovered)}")
    for f in uncovered:
        out.append(f"    {f['path']}  ({f['status']}: {f['reason'] or 'no reason recorded'})")
    out.append(f"  dropped findings: {len(ledger['dropped'])}")
    for d in ledger["dropped"]:
        out.append(f"    {d['shard']}: {d['reason']}")
    all_problems = ledger["problems"] + ledger.get("measure_problems", [])
    out.append(f"  problems: {len(all_problems)}")
    for p in all_problems:
        out.append(f"    {p}")
    out.append(f"  recovered by re-dispatch: {len(ledger.get('recovered', []))}")
    for r in ledger.get("recovered", []):
        out.append(f"    {r}")
    out.append(f"  git status changes during the audit: {len(ledger['git_status_delta'])}")
    for line in ledger["git_status_delta"]:
        out.append(f"    {line}")
    return "\n".join(ascii_safe(line) for line in out)


def titled(prefix, section):
    title, _, rest = section.partition("\n")
    return prefix + title, rest


def cmd_render(args):
    work = Path(args.work)
    inventory = load(work / "inventory.json")
    ledger = load(work / "ledger.json")
    narrative = load(work / "narrative.json")
    properties = inventory["properties"]
    packet_of = {fid: p["id"] for p in ledger.get("packets", []) for fid in p["findings"]}
    dirty = f"dirty ({len(inventory['dirty'])} entries)" if inventory["dirty"] else "clean"
    head = [
        "GREPPABILITY AUDIT",
        "==================",
        f"Repository : {Path(inventory['repo']).name}  {inventory['origin'] or inventory['repo']}",
        f"Revision   : {inventory['head'][:12]}  {inventory['branch']}  {dirty}",
        f"Scope      : {', '.join(inventory['scope']) if inventory['scope'] else 'whole repository'}",
        f"Rubric     : greppable, {len(properties)} properties",
        "Method     : " + wrap(narrative["method"], REPORT_WIDTH - 13, "             ").lstrip(),
        "Provenance : every count is a row in audit.json; bars and glyphs carry their scale on the same line",
    ]
    uncovered = sum(f["status"] == "uncovered" for f in ledger["files"])
    pending = sum(f["status"] == "pending" for f in ledger["files"])
    complete = uncovered == 0 and pending == 0
    head.insert(6, "Coverage   : complete, every hand-written file read in full" if complete else
                f"Coverage   : INCOMPLETE, {uncovered} uncovered and {pending} pending files (see 10. LEDGER); not a whole-repository audit")
    findings = ledger["findings"]
    high = [f for f in findings if f["severity"] == "HIGH"]
    others = [f for f in findings if f["severity"] != "HIGH"]
    body = []
    for f in high:
        body.append(card(f, packet_of))
        body.append("")
    if others:
        body.append("MED and LOW")
        body.extend(one_liner(f, packet_of) for f in others)
    handoff = wrap(
        "Fix in packet order. For each packet: apply every recipe, resolve every decision with the user before "
        "touching it, run the packet's accept lines, then each finding's accept lines. A packet is done when "
        "all accept lines hold and git status shows only files it lists. Full detail with the same IDs is in "
        f"{Path(args.json).name} beside this report (findings[].blast.paths, findings[].recipe, packets[].accept).")
    sections = [
        ("1. VERDICT", wrap(narrative["verdict"])),
        titled("2. ", map_section(ledger)),
        titled("3. ", coverage_table(inventory, ledger) + "\n\n" + exclusion_table(ledger["files"])),
        titled("4. ", heat_section(ledger, properties)),
        titled("5. ", property_ledger(ledger, properties, narrative)),
        titled("6. ", reach_section(ledger.get("trials", []))),
        (f"7. FINDINGS  {len(findings)} accepted, {len(ledger['dropped'])} dropped; HIGH as cards, MED and LOW as one-liners",
         "\n".join(body).rstrip()),
        titled("8. ", packets_section(ledger)),
        ("9. HANDOFF", handoff),
        titled("10. ", appendix(ledger)),
    ]
    parts = ["\n".join(head)] + [f"{title}\n{'-' * len(title)}\n{text}" for title, text in sections]
    report = "\n\n".join(parts) + "\n"
    report = ascii_safe(report)
    Path(args.out).write_text(report)
    audit = {
        "repository": {k: inventory[k] for k in ("repo", "origin", "head", "branch", "dirty", "scope")},
        "rubric": {"path": inventory["rubric"], "properties": properties},
        "narrative": narrative,
        "coverage": {cls: Counter(f["status"] for f in ledger["files"] if f["class"] == cls) for cls in CLASS_ORDER},
        "files": ledger["files"],
        "findings": findings,
        "dropped": ledger["dropped"],
        "trials": ledger.get("trials", []),
        "packets": ledger.get("packets", []),
        "unassigned_findings": ledger.get("unassigned_findings", []),
        "shards": ledger["shards"],
        "problems": ledger["problems"] + ledger.get("measure_problems", []),
        "recovered": ledger.get("recovered", []),
        "git_status_delta": ledger["git_status_delta"],
    }
    dump(args.json, audit)
    print(progress_line(ledger))
    if not complete:
        print(f"incomplete: {uncovered} uncovered and {pending} pending files; do not deliver this as a whole-repository audit")
    print(f"report: {args.out} ({report.count(chr(10))} lines, 7-bit ASCII)  data: {args.json}")


