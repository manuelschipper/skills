    p.add_argument("--work", required=True, help="artifact directory outside the repository")
    p.add_argument("--scope", action="append", default=[], help="restrict to a repository-relative path (repeatable)")
    p.add_argument("--shard-lines", type=int, default=DEFAULT_SHARD_LINES)
