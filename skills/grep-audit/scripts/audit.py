    p.add_argument("--work", required=True)
    p.add_argument("--shard", required=True)
    p.set_defaults(func=cmd_shard_prompt)

    p = sub.add_parser("verify", help="reconcile shard artifacts against assignments and check evidence")
    p.add_argument("--work", required=True)
    p.set_defaults(func=cmd_verify)

    p = sub.add_parser("measure", help="measure blast radii, search trials, and packets")
    p.add_argument("--work", required=True)
    p.set_defaults(func=cmd_measure)

