def coverage_table(inventory, ledger):
    files = ledger["files"] if ledger else inventory["files"]
    rows = []
    total_lines = sum(f["lines"] for f in files)
    unit = max(1, total_lines // 38) if total_lines else 1
    out = [f"COVERAGE                                              scale: one # = {fmt(unit)} lines"]
    out.append(f"  {'class':10} {'files':>6} {'lines':>9}  {'':38}  {'read':>5} {'bndry':>5} {'list':>5} {'uncov':>5} {'pend':>5}")
    for cls in CLASS_ORDER:
        group = [f for f in files if f["class"] == cls]
        if not group:
            continue
        lines = sum(f["lines"] for f in group)
        st = Counter(f.get("status", {"read": "pending", "boundary": "boundary-only", "listed": "listed"}[f["treatment"]]) for f in group)
        mark = bar(lines, unit, 38) if cls in READ_CLASSES else "." * len(bar(lines, unit, 38))
        out.append(f"  {cls:10} {len(group):6d} {fmt(lines):>9}  {mark:38}  {st['read-in-full']:5d} {st['boundary-only']:5d}"
                   f" {st['listed']:5d} {st['uncovered']:5d} {st['pending']:5d}")
        rows.append(cls)
    out.append(f"  {'total':10} {len(files):6d} {fmt(total_lines):>9}")
    out.append("  bars: '#' classes are read in full, '.' classes are boundary-checked or listed only")
    return "\n".join(out)


def exclusion_table(files):
    out = ["EXCLUSIONS  (not read in full; every count is from the inventory)"]
    groups = defaultdict(list)
    for f in files:
        if f["treatment"] != "read":
            groups[(f["class"], f["reason"])].append(f)
    if not groups:
        out.append("  none")
    for (cls, reason), group in sorted(groups.items()):
        dirs = Counter(str(Path(f["path"]).parent) for f in group)
        top = ", ".join(f"{d}/ ({n})" for d, n in dirs.most_common(3))
        out.append(f"  {cls:10} {len(group):5d} files  {fmt(sum(f['lines'] for f in group)):>9} lines  {reason}")
        out.append(f"  {'':10} {'':5}        {'':9}        in {top}")
    return "\n".join(out)


def area_of(path, depth=2):
    parts = Path(path).parts
    return "/".join(parts[:depth]) + "/" if len(parts) > depth else "/".join(parts[:-1]) + "/" if len(parts) > 1 else "./"


def map_section(ledger):
    files = ledger["files"]
    findings = ledger["findings"]
    per_area = defaultdict(lambda: {"files": 0, "lines": 0, "findings": 0, "high": 0, "classes": Counter()})
    for f in files:
        area = area_of(f["path"])
        entry = per_area[area]
        entry["files"] += 1
        entry["lines"] += f["lines"]
        entry["classes"][f["treatment"]] += 1
    for f in findings:
        entry = per_area[area_of(f["path"])]
        entry["findings"] += 1
        entry["high"] += f["severity"] == "HIGH"
    most = max((e["findings"] for e in per_area.values()), default=0)
    unit = max(1, -(-most // 20))
    out = [f"MAP                                                   scale: one # = {unit} findings"]
    out.append(f"  {'area':38} {'files':>6} {'lines':>9}  {'findings':20}  note")
    for area in sorted(per_area):
        e = per_area[area]
        note = []
        if e["high"]:
            note.append(f"{e['high']} HIGH")
        if e["classes"]["boundary"] == e["files"]:
            note.append("boundary only")
        elif e["classes"]["listed"] == e["files"]:
            note.append("listed only")
        out.append(f"  {area:38} {e['files']:6d} {fmt(e['lines']):>9}  {bar(e['findings'], unit, 16):16} {e['findings']:3d}  {', '.join(note)}")
    return "\n".join(out)


def heat_section(ledger, properties):
    findings = ledger["findings"]
    areas = Counter(area_of(f["path"]) for f in findings)
    top = [a for a, _ in areas.most_common(7)]
    rest = sorted(set(areas) - set(top))
    columns = top + (["other"] if rest else [])
    cells = defaultdict(Counter)
    for f in findings:
        area = area_of(f["path"])
        cells[f["property"]][area if area in top else "other"] += 1
    glyph = lambda n: "." if n == 0 else ":" if n <= 2 else "+" if n <= 5 else "#"
    out = ["HEAT GRID  findings per property and area   . = 0   : = 1-2   + = 3-5   # = 6 or more"]
    if not findings:
        return out[0] + "\n  no findings"
    width = 52
    header = "  " + " " * (width + 4) + " ".join(f"{i + 1:>3}" for i in range(len(columns)))
    out.append(header)
    for index, prop in enumerate(properties, 1):
        row = " ".join(f"{glyph(cells[prop][c]):>3}" for c in columns)
        out.append(f"  {index:2d} {prop[:width]:{width}} {row}   {sum(cells[prop].values()):3d}")
    out.append("  columns:")
    for index, column in enumerate(columns, 1):
        label = column if column != "other" else f"other ({len(rest)} areas)"
        out.append(f"    {index:2d} {label}")
    return "\n".join(out)


def property_ledger(ledger, properties, narrative):
    findings = ledger["findings"]
    na = narrative.get("properties_not_applicable", {})
    checks = narrative.get("property_checks", {})
    out = ["PROPERTY LEDGER                                       scale: one # = 1 finding"]
    out.append(f"  {'#':>2} {'property':52} {'HIGH':>4} {'MED':>4} {'LOW':>4}  status")
    for index, prop in enumerate(properties, 1):
        group = [f for f in findings if f["property"] == prop]
        counts = Counter(f["severity"] for f in group)
        if prop in na:
            status = "n/a, because:"
        elif group:
            status = bar(len(group), 1, 24)
        elif checks.get(prop):
            status = "clean, checked by:"
        else:
            status = "UNVERIFIED: no property_checks entry"
        out.append(f"  {index:2d} {prop[:52]:52} {counts['HIGH']:4d} {counts['MED']:4d} {counts['LOW']:4d}  {status}")
        if status.startswith("clean") or prop in na:
            out.append(field("", checks.get(prop) or na.get(prop), gutter=8, label_width=0).replace("         ", "        ", 1))
    out.append(f"  {'total':55} {sum(f['severity'] == 'HIGH' for f in findings):4d}"
               f" {sum(f['severity'] == 'MED' for f in findings):4d} {sum(f['severity'] == 'LOW' for f in findings):4d}")
    return "\n".join(out)


